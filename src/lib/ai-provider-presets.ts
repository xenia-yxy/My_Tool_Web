export function findAiProviderPreset(id: string) {
  return aiProviderPresets.find((preset) => preset.id === id) || null;
}

export function findDefaultAiProviderPreset(provider: AiProvider) {
  return (
    aiProviderPresets.find((preset) => preset.id === provider) ||
    aiProviderPresets.find((preset) => preset.provider === provider) ||
    findAiProviderPreset("custom")
  );
}
